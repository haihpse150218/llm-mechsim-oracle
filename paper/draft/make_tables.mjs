// Generates the data-driven LaTeX tables of the draft from the pilot's result files, so every number in a table is
// traceable to data.   node paper/draft/make_tables.mjs   (run from the idea dir or anywhere)
//   tables/natural.tex   natural errors per mechanism x model (phase 5 + phase 7 generations)
//   tables/repair.tex    final PASS per feedback arm x error kind x model (iterative repair, K = 3)
//   tables/rounds.tex    PASS after each round per arm (pooled file-runs)
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const PILOT = path.resolve(HERE, '../../pilot');
const rd = (p) => fs.readFileSync(path.join(PILOT, p), 'utf8');
const jl = (p) => rd(p).split('\n').filter(Boolean).map(JSON.parse);
fs.mkdirSync(path.join(HERE, 'tables'), {recursive: true});
const out = (name, s) => fs.writeFileSync(path.join(HERE, 'tables', name), s);

// ---------- natural errors ----------
const gens = [...jl('results/gen_lite5.jsonl'), ...jl('results/gen_lite7.jsonl')];
const MECHS = ['four_bar', 'geneva', 'planetary', 'cam', 'watt6', 'jansen', 'lambda', 'peaucellier'];
const NAME = {four_bar: 'Four-bar crank-rocker', geneva: 'Geneva drive', planetary: 'Planetary gear set', cam: 'Disk cam, roller follower', watt6: 'Watt II six-bar', jansen: 'Jansen leg', lambda: 'Chebyshev lambda', peaucellier: 'Peaucellier--Lipkin'};
const KNOW = {jansen: 'published link lengths', lambda: 'published proportions', peaucellier: 'geometric relations', planetary: 'assembly condition', four_bar: 'Grashof condition', geneva: 'tangential pin entry', cam: 'motion law, pressure angle', watt6: 'transmission angle'};
const cell = (mech, model) => {
  const g = gens.filter((r) => r.mech === mech && r.file.includes(`/${model}/`));
  return [g.filter((r) => !r.pass).length, g.length, g.some((r) => !r.pass && r.load && r.load.ok === false)];
};
const fmt = (c) => `${c[0]}/${c[1]}${c[2] ? '\\textsuperscript{a}' : ''}`;
let t = `% generated by make_tables.mjs from pilot/results/gen_lite5.jsonl and gen_lite7.jsonl -- do not edit by hand
\\begin{table}[!htbp]
\\caption{Natural errors: simulators generated from the free-form specification that fail the oracle (5 samples per cell). \\textsuperscript{a}Runtime exception on load, not a violation of the listed design rule.}\\label{tab:natural}
\\begin{tabular}{@{}>{\\raggedright\\arraybackslash}p{2.2cm}>{\\raggedright\\arraybackslash}p{2.4cm}cc@{}}
\\toprule
Mechanism & Design knowledge checked & Haiku & Sonnet \\\\
\\midrule
`;
let tot = [0, 0, 0, 0];
for (const m of MECHS) {
  const h = cell(m, 'haiku'), s = cell(m, 'sonnet');
  tot = [tot[0] + h[0], tot[1] + h[1], tot[2] + s[0], tot[3] + s[1]];
  t += `${NAME[m]} & ${KNOW[m]} & ${fmt(h)} & ${fmt(s)} \\\\\n`;
}
t += `\\midrule\nTotal & & ${tot[0]}/${tot[1]} & ${tot[2]}/${tot[3]} \\\\\n\\botrule\n\\end{tabular}\n\\end{table}\n`;
out('natural.tex', t);

// ---------- repair: final pass by arm x kind x model (from stats/stats.json runs) ----------
const S = JSON.parse(rd('stats/stats.json'));
// deterministic baseline (no LLM): correct values from the spec report written into the page source, graded once
// per source file (pilot/oracle/param_patch.mjs -> results/baseline_patch_src.jsonl)
const patched = new Set(jl('results/baseline_patch_src.jsonl').filter((r) => r.pass).map((r) => r.file.split('/').slice(-2).join('/').replace(/\.html$/, '')));
const runs = S.runs.map((r) => ({...r, param_patch: patched.has(r.file) ? 1 : 0}));
const ARMS = [['oracle_spec', 'Oracle, location + value'], ['oracle_locate', 'Oracle, location only'], ['oracle_coarse', 'Oracle, check + magnitude'], ['vlm', 'VLM review in the loop'], ['none', 'Self-refine (no feedback)']];
const groups = [
  ['Assembly / constraint', (r) => r.kind === 'assembly'],
  ['Haiku', (r) => r.kind === 'design' && r.model === 'haiku'],
  ['Sonnet', (r) => r.kind === 'design' && r.model === 'sonnet'],
  ['All', () => true],
];
t = `% generated by make_tables.mjs from pilot/stats/stats.json -- do not edit by hand
\\begin{table}[!htbp]
\\caption{Iterative repair (at most three rounds): file-runs whose simulator passes the oracle at the end, by feedback arm. Assembly/constraint errors: Watt six-bar, planetary, four-bar crash. Design knowledge: Jansen (phases 5--6) and Chebyshev lambda (phase 7). \\textsuperscript{a}The VLM arm was not run for the lambda file-runs, which are excluded from its counts. \\textsuperscript{b}Deterministic baseline without a repairer: the correct values stated in the location + value report are written into the page source once (Section~\\ref{sec:rq3}).}\\label{tab:repair}
\\begin{tabular}{@{}l${'c'.repeat(groups.length)}@{}}
\\toprule
 & & \\multicolumn{2}{c}{Design knowledge} & \\\\
\\cmidrule(lr){3-4}
Feedback arm & ${groups.map(([g]) => g).join(' & ')} \\\\
\\midrule
`;
for (const [a, label] of [...ARMS, ['param_patch', '\\midrule\nNo LLM: value patch\\textsuperscript{b}']]) {
  const cells = groups.map(([, f]) => {
    const rs = runs.filter(f).filter((r) => r[a] != null);
    const all = runs.filter(f);
    if (!rs.length) return 'n/a';
    const x = rs.filter((r) => r[a]).length;
    return rs.length === all.length ? `${x}/${rs.length}` : `${x}/${rs.length}\\textsuperscript{a}`;
  });
  t += `${label} & ${cells.join(' & ')} \\\\\n`;
}
t += `\\botrule\n\\end{tabular}\n\\end{table}\n`;
out('repair.tex', t);

// ---------- rounds (phase 5-6 pooled 22 file-runs) ----------
const roundsOf = (dir) => JSON.parse(rd(`${dir}/summary.json`)).rows;
const acc = {};
for (const dir of ['iter5/rep1', 'iter5/rep2', 'iter5/abl1', 'iter5/abl2']) {
  for (const r of roundsOf(dir)) {
    const n = Object.entries(r.per).filter(([f, v]) => f !== 'sonnet/geneva_s2' && v === 'PASS').length;
    const of = Object.keys(r.per).filter((f) => f !== 'sonnet/geneva_s2').length;
    const k = `${r.arm}`;
    acc[k] ||= Array.from({length: 4}, () => [0, 0]);
    acc[k][r.round][0] += n; acc[k][r.round][1] += of;
  }
}
t = `% generated by make_tables.mjs from pilot/iter5/*/summary.json -- do not edit by hand
\\begin{table}[!htbp]
\\caption{File-runs passing the oracle after each repair round, phases 5--6 pooled (22 file-runs; round 0 = generated file)}\\label{tab:rounds}
\\begin{tabular}{@{}lcccc@{}}
\\toprule
Arm & r0 & r1 & r2 & r3 \\\\
\\midrule
`;
for (const [a, label] of ARMS) t += `${label.replace('Oracle, ', '')} & ${acc[a].map(([x]) => x).join(' & ')} \\\\\n`;
t += `\\botrule\n\\end{tabular}\n\\end{table}\n`;
out('rounds.tex', t);
console.log('tables written:', fs.readdirSync(path.join(HERE, 'tables')).join(', '));
console.log(fs.readFileSync(path.join(HERE, 'tables/natural.tex'), 'utf8'));
console.log(fs.readFileSync(path.join(HERE, 'tables/repair.tex'), 'utf8'));
console.log(fs.readFileSync(path.join(HERE, 'tables/rounds.tex'), 'utf8'));
